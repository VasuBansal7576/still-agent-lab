import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const install = process.env.STILL_TOOLKIT_INSTALL;
if (!install) throw new Error('Set STILL_TOOLKIT_INSTALL to the directory containing node_modules.');
const require = createRequire(resolve(install, 'package.json'));
const { PayPalAgentToolkit } = require('@paypal/agent-toolkit/openai');
const { Client } = require('@modelcontextprotocol/sdk/client/index.js');
const { StdioClientTransport } = require('@modelcontextprotocol/sdk/client/stdio.js');

// Dummy credentials are never used: tool execution is routed through Still.
const toolkit = new PayPalAgentToolkit({
  clientId: 'unused', clientSecret: 'unused',
  configuration: { actions: { disputes: { get: true }, payments: { createRefund: true } }, context: { sandbox: true } }
});
const tools = toolkit.getTools();
const client = new Client({ name: 'still-toolkit-sdk-bridge', version: '1.0.0' });
const transport = new StdioClientTransport({ command: process.execPath, args: [fileURLToPath(new URL('../server/toolkit-mcp.mjs', import.meta.url)), '--demo'] });
try {
  await client.connect(transport);
  const remote = await client.listTools();
  const names = new Set(remote.tools.map(tool => tool.name));
  for (const tool of tools) if (!names.has(tool.function.name)) throw new Error(`Still does not support ${tool.function.name}`);
  console.log(JSON.stringify({ toolkitTools: tools.map(tool => tool.function.name), gatewayTools: [...names] }));
  const responses = [];
  // These are scripted OpenAI tool calls, not calls generated by a model.
  for (const call of [
    { id: 'dispute-1', function: { name: 'get_dispute', arguments: JSON.stringify({ dispute_id: 'demo-dispute' }) } },
    { id: 'refund-1', function: { name: 'create_refund', arguments: JSON.stringify({ capture_id: 'MOCK-CAPTURE-toolkit', amount: { value: '50.00', currency_code: 'USD' } }) } },
    { id: 'refund-2', function: { name: 'create_refund', arguments: JSON.stringify({ capture_id: 'MOCK-CAPTURE-toolkit', amount: { value: '50.00', currency_code: 'USD' } }) } }
  ]) {
    const result = await client.callTool({ name: call.function.name, arguments: JSON.parse(call.function.arguments) });
    if (result.isError) throw new Error(JSON.stringify(result));
    responses.push(JSON.parse(result.content[0].text));
    console.log(JSON.stringify({ role: 'tool', tool_call_id: call.id, content: result.content }));
  }
  assert.equal(responses[0].body.status, 'CLEAR');
  assert.equal(responses[1].status, 201);
  assert.equal(responses[1].body.id, 'MOCK-REFUND-toolkit-1');
  assert.equal(responses[2].body.id, responses[1].body.id);
} finally {
  await client.close();
}
